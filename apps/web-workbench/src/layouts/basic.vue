    title: '跳转外部链接示例',
    link: 'https://doc.vben.pro',
  },
]);

const { push } = useRouter();
const userStore = useUserStore();
const authStore = useAuthStore();
const accessStore = useAccessStore();
const { destroyWatermark, updateWatermark } = useWatermark();
const showDot = computed(() =>
  notifications.value.some((item) => !item.isRead),
);

const menus = computed(() => [
  {
    handler: () => {
      push({ path: PROFILE_PATH });
    },
    icon: UserOutlined,
    text: $t('ui.profile.title'),
  },
  {
    separator: true,
  },
  {
    handler: () => {
      openWindow(VBEN_DOC_URL, {
        target: '_blank',
      });
    },
    icon: BookOpenText,
    text: $t('ui.widgets.document'),
  },
]);

const avatarUrl = ref<string>();
watch(
  () => userStore.userInfo,
  async (obj) => {
    if (!obj?.avatar) {
      return;
    }
    const res = await findUrlByObject(
      FileObjectType.console.user.avatar,
      obj?.avatar as string,
    );
    const file = Object.values(res)?.[0];
    avatarUrl.value = file?.url;
  },

  { immediate: true }, // 初始化时立即执行一次
);

const avatar = computed(() => {
  return avatarUrl.value ?? preferences.app.defaultAvatar;
});
async function handleLogout() {
  await authStore.logout(false);
}

async function handleSignout() {
  await authStore.signout(false);
}

function handleNoticeClear() {
  notifications.value = [];
}

function markRead(id: number | string) {
  const item = notifications.value.find((item) => item.id === id);
  if (item) {
    item.isRead = true;
  }
}

function remove(id: number | string) {
  notifications.value = notifications.value.filter((item) => item.id !== id);
}

function handleMakeAll() {
  notifications.value.forEach((item) => (item.isRead = true));
}
watch(
  () => ({
    enable: preferences.app.watermark,
    content: preferences.app.watermarkContent,
  }),
  async ({ enable, content }) => {
    if (enable) {
      await updateWatermark({
        content:
          content ||
          `${userStore.userInfo?.username} - ${userStore.userInfo?.name}`,
      });
    } else {
      destroyWatermark();
    }
  },
  {
    immediate: true,
  },
);
</script>

<template>
  <BasicLayout :logo-width="70" @clear-preferences-and-logout="handleLogout">
    <template #user-dropdown>
      <UserDropdown
        :avatar
        :menus
        :text="userStore.userInfo?.name"
        description="ann.vben@gmail.com"
        tag-text="Pro"
        @logout="handleLogout"
        @signout="handleSignout"
      />
    </template>
    <template #notification>
      <Notification
        :dot="showDot"
        :notifications="notifications"
        @clear="handleNoticeClear"
        @read="(item) => item.id && markRead(item.id)"
        @remove="(item) => item.id && remove(item.id)"
        @make-all="handleMakeAll"
      />
    </template>
    <template #extra>
      <AuthenticationLoginExpiredModal
        v-model:open="accessStore.loginExpired"
        :avatar
      >
        <LoginForm />
      </AuthenticationLoginExpiredModal>
    </template>
    <template #lock-screen>
      <LockScreen :avatar @to-login="handleLogout" />
    </template>
  </BasicLayout>
</template>
